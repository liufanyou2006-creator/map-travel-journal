// Optional end-to-end verification: requires Playwright and Chrome installed.
// node tests/browser-smoke.cjs <generated-site> <screenshot-directory>
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const {spawn}=require('node:child_process');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const root=path.resolve(__dirname,'..'),site=path.resolve(process.argv[2]),screens=path.resolve(process.argv[3]||path.join(root,'work/browser-smoke'));
(async()=>{
  await fs.mkdir(screens,{recursive:true});
  const server=spawn(process.execPath,[path.join(root,'skills/travel-journal/scripts/serve.mjs'),'--directory',site,'--port','8178'],{stdio:['ignore','pipe','pipe'],windowsHide:true});
  let browser;
  try{
    await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('Preview server did not start')),10000);server.once('error',reject);server.stdout.once('data',()=>{clearTimeout(timer);resolve();});server.stderr.once('data',d=>{clearTimeout(timer);reject(Error(String(d)));});});
    browser=await chromium.launch({channel:'chrome',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
    const context=await browser.newContext({viewport:{width:1600,height:1000},acceptDownloads:true});
    const page=await context.newPage(),errors=[],localFailures=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('response',r=>{if(r.url().startsWith('http://127.0.0.1:8178')&&r.status()>=400)localFailures.push(r.url()+' '+r.status());});
    await page.goto('http://127.0.0.1:8178',{waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>typeof window.TRAVEL_JOURNAL==='object'&&document.querySelector('#route-summary').textContent.includes('旧金山'));
    assert.equal(await page.evaluate(()=>window.journalMediaReady),true,'generated media must be cached');
    assert.deepEqual(await page.evaluate(()=>state.trips.map(t=>t.name)),['San Francisco','Seattle']);
    assert.equal(await page.evaluate(()=>state.trips.length),2,'no unrelated global examples inserted');
    await page.locator('.directory-land').waitFor();
    await page.screenshot({path:path.join(screens,'cover.png')});
    await page.waitForFunction(()=>mapReady,{},{timeout:30000});
    await page.evaluate(()=>startPlayback());
    await page.waitForFunction(()=>playback.running);
    await page.locator('#pause-play').click();
    assert.equal(await page.evaluate(()=>playback.paused),true);
    await page.locator('#exit-play').click();
    await page.evaluate(()=>previewCity(state.trips[0].id));
    await page.waitForFunction(()=>document.querySelector('#film-stage').classList.contains('tools-folded'));
    await page.screenshot({path:path.join(screens,'city.png')});
    await page.evaluate(async()=>{const t=state.trips[0];await openMediaSettings(t.id,t.stops[1].id);});
    await page.locator('#studio-artboard img').first().waitFor();
    await page.screenshot({path:path.join(screens,'editor.png')});
    await page.locator('#studio-note-edit').click();
    await page.locator('#studio-note-text').fill('浏览器验证：保存我的旅行文字。');
    await page.locator('#studio-note-save').click();
    await page.reload({waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>state.trips[0].stops[1].note==='浏览器验证：保存我的旅行文字。');
    assert.equal(await page.evaluate(()=>window.journalMediaReady),true);
    await page.evaluate(()=>openBackup());
    const downloadPromise=page.waitForEvent('download');
    await page.locator('#export-backup').click();
    const download=await downloadPromise;const backupPath=path.join(screens,'backup.json');await download.saveAs(backupPath);
    const backupText=await fs.readFile(backupPath,'utf8'),backup=JSON.parse(backupText);
    assert.equal(backup.format,'along-the-way-backup');assert.equal(backup.files.length,6);
    const designBefore=backup.state.trips[0].stops[1].design;
    assert.ok(designBefore.pages.some(p=>p.elements.some(e=>e.kind==='media')));
    await page.evaluate(async text=>{state.trips=[];save();await restoreBackup(text);},backupText);
    await page.locator('#confirm-restore').click();
    await page.waitForFunction(()=>state.trips.length===2&&state.trips[0].stops[1].note==='浏览器验证：保存我的旅行文字。');
    const restored=await page.evaluate(()=>{const s=state.trips[0].stops[1];return {ids:s.media.map(m=>m.id),design:s.design};});
    assert.ok(restored.design.pages.every(p=>p.elements.filter(e=>e.kind==='media').every(e=>restored.ids.includes(e.mediaId))),'restored layout references must follow restored media IDs');
    await page.evaluate(()=>openBackup());
    const chooserPromise=page.waitForEvent('filechooser');await page.locator('#merge-backup').click();
    const chooser=await chooserPromise;await chooser.setFiles(backupPath);
    await page.locator('#merge-confirm').waitFor();await page.locator('#merge-confirm').click();
    await page.waitForFunction(()=>!document.querySelector('#editor').open);
    await page.reload({waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>state.trips.length===2);
    assert.equal(await page.evaluate(()=>state.trips[0].stops[1].note),'浏览器验证：保存我的旅行文字。');
    assert.equal(await page.evaluate(()=>localStorage.getItem('along-the-way-v1')),null,'merge must use the journal namespace');
    // New seed on the same origin must not erase the browser's edits.
    await page.evaluate(()=>{const saved=JSON.parse(localStorage.getItem(journalStorageKey));saved.settings.journalSeedRevision='earlier-seed';localStorage.setItem(journalStorageKey,JSON.stringify(saved));});
    await page.reload({waitUntil:'domcontentloaded'});
    await page.locator('#journal-apply-seed').waitFor();
    assert.equal(await page.evaluate(()=>state.trips[0].stops[1].note),'浏览器验证：保存我的旅行文字。');
    await page.locator('#journal-keep-local').click();
    await page.evaluate(()=>showJournalRevision());await page.locator('#journal-apply-seed').click();
    assert.notEqual(await page.evaluate(()=>state.trips[0].stops[1].note),'浏览器验证：保存我的旅行文字。');
    await page.evaluate(()=>about.onclick());
    await page.getByRole('button',{name:'恢复上次应用版本前的文字与排版'}).click();
    assert.equal(await page.evaluate(()=>state.trips[0].stops[1].note),'浏览器验证：保存我的旅行文字。');
    const phone=await context.newPage();await phone.setViewportSize({width:390,height:844});
    await phone.goto('http://127.0.0.1:8178',{waitUntil:'domcontentloaded'});
    await phone.evaluate(()=>{if(document.querySelector('#editor').open)closeDialog();});
    await phone.screenshot({path:path.join(screens,'phone.png')});
    assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'phone page must not overflow horizontally');
    assert.deepEqual(errors,[],'no uncaught page exceptions');assert.deepEqual(localFailures,[],'no missing local assets');
    console.log(JSON.stringify({ok:true,checks:['cover','play/pause','city','editor','reload persistence','portable backup/restore','layout/media references','seed version preservation','phone layout'],screenshots:screens}));
  }finally{if(browser)await browser.close();server.kill();}
})().catch(error=>{console.error(error);process.exitCode=1;});
